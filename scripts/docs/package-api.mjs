// Read defining exports as TypeScript; documentation never executes author modules.
import { existsSync, globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import ts from '@typescript/typescript6';
import { authoringGuide, checkAuthoringExamples } from './authoring-reference.mjs';

/** Concrete public source modules, including wildcard exports and conditional type targets. */
export function publicModules(folder) {
  const manifest = JSON.parse(readFileSync(resolve(folder, 'package.json'), 'utf8'));
  return Object.entries(manifest.exports).flatMap(([key, value]) => {
    const target = typeof value === 'string' ? value : value.types ?? value.import ?? value.default;
    if (typeof target !== 'string' || !target.startsWith('./')) throw new Error(`Unsupported public export ${manifest.name}${key}`);
    if (!/\.(?:[cm]?[jt]s)$/u.test(target)) return [];
    const paths = target.includes('*') ? globSync(target, { cwd: folder }).sort().map(path => `./${path}`) : [target];
    const [before = '', after = ''] = target.split('*');
    return paths.filter(path => !/\.(?:test|spec)\.[cm]?[jt]s$/u.test(path)).map(path => {
      const stem = path.slice(before.length, after === '' ? undefined : -after.length);
      const subpath = key.includes('*') ? key.replace('*', stem) : key;
      const file = resolve(folder, path);
      if (!existsSync(file)) throw new Error(`Missing public module ${file}`);
      return { from: `${manifest.name}${subpath === '.' ? '' : subpath.slice(1)}`, file };
    });
  });
}

const firstLine = text => text.split('\n').map(line => line.trim()).find(Boolean) ?? '';
function kindOf(symbol) {
  for (const [flag, kind] of [[ts.SymbolFlags.Class, 'class'], [ts.SymbolFlags.Function, 'function'],
    [ts.SymbolFlags.Interface, 'interface'], [ts.SymbolFlags.TypeAlias, 'type'], [ts.SymbolFlags.Enum, 'enum'],
    [ts.SymbolFlags.Variable, 'const'], [ts.SymbolFlags.Module, 'namespace']]) if (symbol.flags & flag) return kind;
  return 'other';
}

/** SDK, installed format and workspace kit bindings, independent of engine context interfaces. */
export function packageApiSurface(root) {
  const folders = { sharddev: root, format: resolve(root, 'node_modules/@wildshard/format'), kit: resolve(root, 'packages/kit') };
  const modules = Object.fromEntries(Object.entries(folders).map(([name, folder]) => [name, publicModules(folder)]));
  const config = ts.readConfigFile(resolve(root, 'tsconfig.json'), ts.sys.readFile);
  if (config.error !== undefined) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
  const program = ts.createProgram(Object.values(modules).flat().map(row => row.file), { ...parsed.options, allowJs: true, noEmit: true });
  const checker = program.getTypeChecker(), indexes = {};
  for (const [name, entries] of Object.entries(modules)) {
    indexes[name] = entries.flatMap(({ from, file }) => {
      const source = program.getSourceFile(file), symbol = source === undefined ? undefined : checker.getSymbolAtLocation(source);
      if (symbol === undefined) throw new Error(`Cannot read public module ${relative(root, file)}`);
      return checker.getExportsOfModule(symbol).map(binding => {
        const target = binding.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(binding) : binding;
        return { name: binding.getName(), kind: kindOf(target), from, doc: firstLine(ts.displayPartsToString(target.getDocumentationComment(checker))) };
      });
    }).sort((a, b) => a.from.localeCompare(b.from) || a.name.localeCompare(b.name));
  }
  return { indexes, contexts: {} };
}

function apiPage(title, rows) {
  const escape = text => text.replaceAll('|', String.raw`\|`);
  return `# ${title}\n\n> Written by: Codex\n\n> **State:** generated API for the installed package pins; run \`pnpm run docs\`.\n\n<!-- Generated by scripts/docs.mjs from defining package exports. -->\n\n${rows.length} exported bindings.\n\n| Member | Kind | From | What it is |\n|---|---|---|---|\n${rows.map(row => `| \`${row.name}\` | ${row.kind} | ${row.from} | ${escape(row.doc) || '—'} |`).join('\n')}\n`;
}

/** Exact checked examples accompany the public tables; source and rendered snippets have one owner. */
export function packageApiDocuments(root, surface = packageApiSurface(root)) {
  return {
    'docs/api/SHARDDEV.md': `${apiPage('@wildshard/sdk', surface.indexes.sharddev)}\n${authoringGuide(resolve(root, 'scripts/docs'))}`,
    'docs/api/FORMAT.md': apiPage('@wildshard/shard-format', surface.indexes.format),
    'docs/api/KIT.md': apiPage('@wildshard/kit', surface.indexes.kit),
  };
}

/** Validate examples before changing documentation, then write only changed outputs. */
export function writePackageApi(root) {
  const failures = checkAuthoringExamples(root);
  if (failures.length > 0) throw new Error(failures.join('\n'));
  const surface = packageApiSurface(root), documents = packageApiDocuments(root, surface);
  for (const [file, text] of Object.entries(documents)) {
    const path = resolve(root, file);
    if (existsSync(path) && readFileSync(path, 'utf8') === text) continue;
    mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text);
  }
  return surface;
}
