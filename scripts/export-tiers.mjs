// SHARD-AUTHORING SA5 (J317): every @wildshard/sdk export is in one tier (lint/export-tiers.json): contract, rows,
// scripts, bake kit or internal. `exportTierProblems` names each unclassed export, stale row and unknown tier;
// `renderExportTiers` is docs/api/EXPORT-TIERS.md, the API doc that shows each export's tier.
//   node scripts/export-tiers.mjs           write docs/api/EXPORT-TIERS.md
//   node scripts/export-tiers.mjs --check   fail on a problem or a stale page
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
export const TIERS = ['contract', 'rows', 'scripts', 'bake kit', 'internal'];
export const TIER_FILE = 'lint/export-tiers.json';
export const TIER_PAGE = 'docs/api/EXPORT-TIERS.md';

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
/** The package's exports and the tier file, read from `root`.
 * @param {string} [root] @returns {{ exports: Record<string, unknown>, tiers: { tiers: Record<string, string>, exports: Record<string, string> } }} */
export function readExportTiers(root = ROOT) {
  return { exports: readJson(resolve(root, 'package.json')).exports ?? {}, tiers: readJson(resolve(root, TIER_FILE)) };
}
/** One line per problem; empty when every export has exactly one known tier and every row names an export.
 * @param {Record<string, unknown>} exports @param {{ tiers: Record<string, string>, exports: Record<string, string> }} tiers @returns {string[]} */
export function exportTierProblems(exports, tiers) {
  const problems = [];
  for (const tier of TIERS) if (typeof tiers.tiers?.[tier] !== 'string') problems.push(`tier "${tier}" has no description in ${TIER_FILE}`);
  for (const tier of Object.keys(tiers.tiers ?? {})) if (!TIERS.includes(tier)) problems.push(`unknown tier "${tier}" in ${TIER_FILE}`);
  for (const subpath of Object.keys(exports)) {
    const tier = tiers.exports?.[subpath];
    if (tier === undefined) problems.push(`unclassed export ${subpath}: give it a tier (${TIERS.join(', ')}) in ${TIER_FILE}`);
    else if (!TIERS.includes(tier)) problems.push(`export ${subpath} has unknown tier "${tier}"`);
  }
  for (const subpath of Object.keys(tiers.exports ?? {})) if (!Object.hasOwn(exports, subpath)) problems.push(`${TIER_FILE} classes ${subpath}, which package.json does not export`);
  return problems;
}
const specifier = (subpath) => `@wildshard/sdk${subpath === '.' ? '' : `/${subpath.slice(2)}`}`;
const target = (value) => (typeof value === 'string' ? value : JSON.stringify(value));
/** docs/api/EXPORT-TIERS.md: each tier, what it promises, and its exports with the file each resolves to.
 * @param {Record<string, unknown>} exports @param {{ tiers: Record<string, string>, exports: Record<string, string> }} tiers @returns {string} */
export function renderExportTiers(exports, tiers) {
  const sections = TIERS.map((tier) => {
    const rows = Object.keys(exports).filter((subpath) => tiers.exports[subpath] === tier).sort();
    return `## ${tier} (${rows.length})\n\n${tiers.tiers[tier]}\n\n| Export | Tier | File |\n|---|---|---|\n${rows.map((subpath) => `| \`${specifier(subpath)}\` | ${tier} | \`${target(exports[subpath])}\` |`).join('\n')}\n`;
  });
  return `# @wildshard/sdk exports, by tier\n\n<!-- generated by scripts/export-tiers.mjs from package.json exports and ${TIER_FILE}: do not edit -->\n\n${Object.keys(exports).length} exports. A shard project imports from contract, rows, scripts and the bake kit; internal may change in any release. A new export needs a row in \`${TIER_FILE}\` (\`test/export-tiers.test.ts\` fails without one); then run \`node scripts/export-tiers.mjs\`.\n\n${sections.join('\n')}`;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { exports, tiers } = readExportTiers(ROOT), problems = exportTierProblems(exports, tiers);
  if (problems.length > 0) { console.error(problems.join('\n')); process.exit(1); }
  const page = renderExportTiers(exports, tiers), path = resolve(ROOT, TIER_PAGE);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* missing reads as stale */ }
    if (current !== page) { console.error(`${TIER_PAGE} is stale: run node scripts/export-tiers.mjs`); process.exit(1); }
  } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, page); }
  console.info(`export tiers: ${Object.keys(exports).length} exports classed`);
}
